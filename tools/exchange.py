"""Dependency-free interchange helpers, shared by CLI and Blender."""
import hashlib
import json
import math
import struct
from pathlib import Path

CONTRACT = 'cosmosys.cad.controls'
CONTRACT_VERSION = 1


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def yaml_text(filename, controls, presentation=None):
    # JSON scalar encodings are valid YAML, including quoted model/control keys.
    lines = ['# Generated by cosmosys_arch_toolkit. Edit the .blend, not this file.',
             '# glTF Y-up; metres/degrees; offsets from zero rest pose.', 'models:',
             f'  {json.dumps(filename, ensure_ascii=False)}:', '    rotation_order: XYZ']
    for key, vector in sorted((presentation or {}).items()):
        if key not in ('rotation_degrees', 'translation') or len(vector) != 3 or not all(isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v) for v in vector):
            raise ValueError('Preferencias de presentación inválidas')
        lines.append(f'    {key}: {json.dumps(list(vector), allow_nan=False)}')
    lines.append('    controls:' if controls else '    controls: {}')
    for key, definition in sorted(controls.items()):
        lines.append(f'      {json.dumps(key, ensure_ascii=False)}:')
        for name, value in definition.items():
            lines.append(f'        {name}: {json.dumps(value, ensure_ascii=False, allow_nan=False)}')
    return '\n'.join(lines) + '\n'


def verify_pair(glb, yaml):
    glb, yaml = Path(glb), Path(yaml)
    with glb.open('rb') as stream:
        header = stream.read(20)
        if len(header) != 20:
            raise ValueError('GLB truncado: falta la cabecera.')
        magic, version, size, length, kind = struct.unpack('<4s4I', header)
        if magic != b'glTF' or version != 2 or size != glb.stat().st_size or kind != 0x4E4F534A:
            raise ValueError('Cabecera GLB 2.0 inválida.')
        if length > 32 * 1024 * 1024 or length > size - 20:
            raise ValueError('Chunk JSON inválido o mayor de 32 MiB.')
        document = json.loads(stream.read(length))
    if not isinstance(document, dict):
        raise ValueError('El documento GLB debe ser un objeto JSON.')
    nodes = document.get('nodes', [])
    if not isinstance(nodes, list) or any(not isinstance(node, dict) for node in nodes):
        raise ValueError('Inventario de nodos GLB inválido.')
    names = [node.get('name') for node in nodes]
    if not nodes or any(not isinstance(name, str) or not name for name in names) or len(set(names)) != len(names):
        raise ValueError('Los nodos GLB deben tener nombres únicos y no vacíos.')
    if len(document.get('scenes', [])) != 1 or document.get('animations') or document.get('cameras'):
        raise ValueError('Se esperaba una escena sin cámaras ni animaciones.')
    controls, schemas = {}, []
    for node in nodes:
        extras = node.get('extras', {})
        if not isinstance(extras, dict):
            raise ValueError('Extras GLB inválidos.')
        if extras.get('cosmosys_model'):
            schemas.append(extras['cosmosys_model'])
        annotations = extras.get('cosmosys_controls', {})
        if not isinstance(annotations, dict):
            raise ValueError('Anotaciones de controles inválidas.')
        for key, definition in annotations.items():
            if not key.strip() or not isinstance(definition, dict):
                raise ValueError('Definición de control inválida.')
            if key in controls or definition.get('target_node') != node['name']:
                raise ValueError(f'Control duplicado o con objetivo incorrecto: {key}')
            if definition.get('transform') not in ('rotation', 'position') or definition.get('space') not in ('local', 'global') or definition.get('axis') not in ('x', 'y', 'z'):
                raise ValueError(f'Movimiento no soportado: {key}')
            minimum, maximum, step = [definition.get(field) for field in ('min', 'max', 'step')]
            if not all(isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value) for value in (minimum, maximum, step)):
                raise ValueError(f'Límites no finitos: {key}')
            if not minimum <= 0 <= maximum or minimum >= maximum or step <= 0:
                raise ValueError(f'Límites/paso inválidos: {key}')
            if 'round_decimals' in definition and (type(definition['round_decimals']) is not int or not 0 <= definition['round_decimals'] <= 15):
                raise ValueError(f'round_decimals inválido: {key}')
            controls[key] = definition
    if len(schemas) != 1 or not isinstance(schemas[0], dict) or schemas[0].get('schema') != CONTRACT or schemas[0].get('version') != CONTRACT_VERSION:
        raise ValueError('Contrato de controles ausente, duplicado o no soportado.')
    # This verifies the toolkit's own canonical YAML, not arbitrary hand-edited YAML.
    if yaml.read_text(encoding='utf8') != yaml_text(glb.name, controls, schemas[0].get('presentation')):
        raise ValueError('El YAML no coincide con los controles GLB o no tiene el formato canónico del toolkit.')
    return {'nodes': len(nodes), 'controls': len(controls), 'glb_sha256': sha256(glb), 'yaml_sha256': sha256(yaml)}
